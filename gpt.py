class GPTAnalyzer:
    def __init__(self, api_key: str, model: str) -> None:
        self._client = AsyncOpenAI(api_key=api_key)
        self._model = model

    def _is_reasoning_model(self) -> bool:
        m = self._model.lower()
        return m.startswith(("gpt-5", "o1", "o3", "o4"))

    async def analyze(self, payload: dict[str, Any], mode: str = "full") -> str:
        instructions = MODE_INSTRUCTIONS.get(mode, MODE_INSTRUCTIONS["full"])
        has_sales = bool(payload.get("sales"))
        sales_note = (
            "\n\nУ тебя ЕСТЬ реальные данные продаж из WB Statistics API "
            "(см. поле `sales`: выручка, средний чек, конверсия заказ→выкуп, "
            "возвраты, топ SKU по выручке, дневная динамика). "
            "Опирайся именно на них при оценках спроса, тренда и ценовых "
            "решений. Где сигналы из карточек противоречат продажам — "
            "доверяй продажам."
            if has_sales
            else "\n\nДанных продаж нет (анализируется чужой магазин или "
            "не задан WB_SUPPLIER_TOKEN) — работай по публичным сигналам "
            "(feedbacks, рейтинги, остатки, цены)."
        )
        user_content = (
            "Сводка по магазину (JSON):\n```json\n"
            + json.dumps(payload, ensure_ascii=False, indent=2)
            + "\n```"
            + sales_note
            + "\n\nЗадача:\n"
            + instructions
        )
        kwargs: dict[str, Any] = {
            "model": self._model,
            "messages": [
                {"role": "system", "content": BASE_SYSTEM},
                {"role": "user", "content": user_content},
            ],
        }
        if not self._is_reasoning_model():
            kwargs["temperature"] = 0.4
        resp = await self._client.chat.completions.create(**kwargs)
        content = resp.choices[0].message.content or ""
        return content.strip()
