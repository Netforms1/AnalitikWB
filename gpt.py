class GPTAnalyzer:
    def __init__(self, api_key: str, model: str) -> None:
        self._client = AsyncOpenAI(api_key=api_key)
        self._model = model

    def _is_reasoning_model(self) -> bool:
        m = self._model.lower()
        return m.startswith(("gpt-5", "o1", "o3", "o4"))

    async def analyze(self, payload: dict[str, Any], mode: str = "full") -> str:
        instructions = MODE_INSTRUCTIONS.get(mode, MODE_INSTRUCTIONS["full"])
        has_sales = bool(payload.get("sales"))
        sales_note = (
            "\n\nУ тебя ЕСТЬ блок sales с реальными продажами из WB Statistics API. "
            "Опирайся на него для оценок спроса, тренда и ценовых решений. "
            "Где сигналы из карточек противоречат продажам — доверяй продажам."
            if has_sales
            else "\n\nДанных продаж нет (анализируется чужой магазин или не "
            "задан WB_SUPPLIER_TOKEN) — работай по публичным сигналам "
            "(feedbacks, рейтинги, остатки, цены)."
        )
        user_content = (
            "Сводка по магазину (JSON):\n```json\n"
            + json.dumps(payload, ensure_ascii=False, indent=2)
            + "\n```"
            + sales_note
            + "\n\nЗадача:\n"
            + instructions
            + "\n\nНапомню: ответ строго в HTML, без markdown, по описанным "
            "правилам форматирования. Не оборачивай ответ в ```html```."
        )
        kwargs: dict[str, Any] = {
            "model": self._model,
            "messages": [
                {"role": "system", "content": BASE_SYSTEM},
                {"role": "user", "content": user_content},
            ],
        }
        if not self._is_reasoning_model():
            kwargs["temperature"] = 0.4
        resp = await self._client.chat.completions.create(**kwargs)
        content = resp.choices[0].message.content or ""
        return _sanitize_html(content.strip())


_ALLOWED_TAGS = {
    "b", "strong", "i", "em", "u", "ins", "s", "strike", "del",
    "code", "pre", "blockquote", "a", "br", "tg-spoiler", "span",
}


def _sanitize_html(text: str) -> str:
    """Приводим вывод GPT к Telegram-совместимому HTML.

    1. Снимаем обёртку ```html ... ``` если модель её добавила.
    2. Убираем markdown-заголовки (### и т.п.) если просочились.
    """
    import re

    text = text.strip()
    # ```html ... ```
    if text.startswith("```"):
        text = re.sub(r"^```(?:html)?\s*\n?", "", text)
        text = re.sub(r"\n?```\s*$", "", text)
    # Markdown-заголовки → <b>...</b>
    text = re.sub(r"^(#{1,6})\s+(.+)$", r"<b>\2</b>", text, flags=re.MULTILINE)
    # **bold** → <b>bold</b>
    text = re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)
    # *italic* (отдельные звёздочки) → <i>...</i> — только если оба края — звёздочки и нет пробелов сразу за ними
    text = re.sub(r"(?<!\*)\*(?!\s)([^*\n]+?)(?<!\s)\*(?!\*)", r"<i>\1</i>", text)
    return text.strip()
